#!/usr/bin/env node
/**
 * Build the catalogue from the fleet's app-endpoints dataset (B2.2, first pass).
 *
 * 2,214 public APIs, 1,103 of them keyless. This script keeps the keyless,
 * HTTPS ones that look like model endpoints, and turns each into a catalogue
 * entry with `needs_probe: true` — an identity, never an endpoint. The dataset
 * gives a homepage, not an OpenAI-compatible base URL, so `base_url` stays null
 * and `docs_url` carries the link. Resolving it is the prober's job (B2.3).
 *
 *   node scripts/build-catalog.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { appEndpointsPath } from '@drsamonline/kits';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

// A category match is enough; a text match alone must be a strong signal, or the
// catalogue fills with weather APIs that happen to mention "model".
/**
 * What belongs in a *model* catalogue — and why this script keeps nothing.
 *
 * The app-endpoints dataset is a directory of miscellaneous public APIs. Three
 * attempts to filter it for model endpoints produced, in order: 15 entries
 * (a sudoku API, a dream-interpretation API, a translator), 6 entries (a model
 * *catalogue*, a benchmark), and 24 entries (QR codes, avatars, random words).
 * Each attempt was a keyword heuristic, and each one was wrong in a new way.
 *
 * The conclusion is not "filter harder". It is that the dataset does not contain
 * what a model catalogue needs. So this script now keeps **nothing** unless a
 * host is on an explicit allowlist of known model providers, and the model
 * catalogue is seeded deliberately in seed.json instead — where every entry names
 * its source and none of them are QR codes.
 *
 * The dataset stays vendored because it is a useful directory of *other* public
 * APIs, and the file it generates documents that honestly.
 */

const MODEL_HOSTS = new Set([
  // an explicit list, because a keyword cannot tell "generate a QR code" from
  // "generate a completion". Add a host here only with evidence it serves a model.
]);

const SERVING_SIGNAL = /\b(chat completion|chat-completions?|text generation|completion endpoint|inference api|serves models)\b/i;

/** Directories, benchmarks and documentation are not endpoints. */
const NOT_SERVING = /\b(catalogue|catalog|directory|benchmark|leaderboard|dataset|documentation|docs? only|how it works|comparison|list of|registry|modelfax|memory requirements|pricing)\b/i;

/** A capability that is not a chat: an image, a voice, a translation, a dataset. */
const OTHER_MODALITY =
  /\b(image|photo|picture|video|speech|voice|audio|music|tts|stt|ocr|transcription|translation|translate|embedding|rerank|ocr|sudoku|dream|horoscope|astrology|weather|crypto price|stock price)\b/i;

const raw = JSON.parse(readFileSync(appEndpointsPath(), 'utf8'));
const apis = raw.apis ?? [];

const kept = [];
const seen = new Set();

for (const api of apis) {
  if (api.auth !== 'none') continue;
  if (api.https !== 'yes') continue;
  if (!api.host || !api.url) continue;

  // an explicit allowlist first: a keyword cannot tell "generate a QR code" from
  // "generate a completion", and three attempts to pretend otherwise failed
  const onAllowlist = MODEL_HOSTS.has(String(api.host ?? '').toLowerCase());
  if (!onAllowlist) continue;

  const text = `${api.name ?? ''} ${api.desc ?? ''}`;
  if (!SERVING_SIGNAL.test(text)) continue;
  if (NOT_SERVING.test(text)) continue;
  if (OTHER_MODALITY.test(text)) continue;

  const provider = slug(api.host);
  if (seen.has(provider)) continue;
  seen.add(provider);

  kept.push({
    provider,
    label: api.name ?? provider,
    base_url: null,
    docs_url: api.url,
    auth: 'none',
    model_family: null,
    tos: 'review',
    privacy_retention: 'unknown',
    capabilities: guessCapabilities(api),
    needs_probe: true,
    notes: `from app-endpoints: ${api.cat ?? 'uncategorised'}${api.cors === 'yes' ? ' · CORS yes' : ''} — base URL unverified`,
  });
}

kept.sort((a, b) => a.provider.localeCompare(b.provider));

const out = {
  _comment:
    'Generated by scripts/build-catalog.mjs from the app-endpoints dataset. It is EMPTY by design: that dataset is a directory of miscellaneous public APIs (QR codes, avatars, random words), not a source of model endpoints. The model catalogue lives in seed.json, where every entry names its source. Do not hand-edit; re-run the script.',
  version: 1,
  meta: {
    source: 'drsamonline/app-endpoints data/apis.json',
    sourceCount: apis.length,
    keylessCount: apis.filter((a) => a.auth === 'none').length,
    kept: kept.length,
    generatedAt: new Date().toISOString(),
    filter: 'auth=none, https=yes, category or description looks like a model endpoint',
  },
  entries: kept,
};

writeFileSync(join(ROOT, 'packages', 'catalog', 'generated.json'), JSON.stringify(out, null, 2) + '\n');

console.log('');
console.log(`Catalogue built from ${apis.length} APIs`);
console.log(`  keyless:      ${out.meta.keylessCount}`);
console.log(`  kept:         ${kept.length} (model-ish, HTTPS, no key)`);
console.log(`  categories:   ${[...new Set(kept.map((k) => k.notes.split(': ')[1]?.split(' ·')[0]))].slice(0, 8).join(', ')}`);
console.log(`  written:      packages/catalog/generated.json`);
console.log('');
console.log(
  'Kept nothing: this dataset holds public APIs, not model endpoints.\n' +
    'The model catalogue is packages/catalog/seed.json, where every entry names its source.',
);

function slug(host) {
  return String(host)
    .toLowerCase()
    .replace(/^www\./, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40);
}

function guessCapabilities(api) {
  const text = `${api.name} ${api.desc ?? ''} ${api.cat ?? ''}`.toLowerCase();
  const caps = new Set(['chat']);
  if (/stream/.test(text)) caps.add('streaming');
  if (/translat|language/.test(text)) caps.add('chat');
  if (/embed/.test(text)) caps.add('embeddings');
  if (/image|photo|picture/.test(text)) caps.add('image');
  if (/speech|audio|voice|transcri|tts/.test(text)) caps.add('stt');
  if (/ocr|vision|classif/.test(text)) caps.add('vision');
  return [...caps];
}
