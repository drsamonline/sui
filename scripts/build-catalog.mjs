#!/usr/bin/env node
/**
 * Build the catalogue from the fleet's app-endpoints dataset (B2.2, first pass).
 *
 * 2,214 public APIs, 1,103 of them keyless. This script keeps the keyless,
 * HTTPS ones that look like model endpoints, and turns each into a catalogue
 * entry with `needs_probe: true` — an identity, never an endpoint. The dataset
 * gives a homepage, not an OpenAI-compatible base URL, so `base_url` stays null
 * and `docs_url` carries the link. Resolving it is the prober's job (B2.3).
 *
 *   node scripts/build-catalog.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { appEndpointsPath } from '@sui/kits';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

// A category match is enough; a text match alone must be a strong signal, or the
// catalogue fills with weather APIs that happen to mention "model".
const RELEVANT_CATEGORIES = /^(machine learning|artificial intelligence|ai|text analysis|language|translation|images|audio|science)$/i;
const RELEVANT_TEXT = /\b(llm|gpt|chat completion|chat-completion|language model|inference|embedding|text generation|image generation|speech.to.text|text.to.speech|ocr)\b/i;

const raw = JSON.parse(readFileSync(appEndpointsPath(), 'utf8'));
const apis = raw.apis ?? [];

const kept = [];
const seen = new Set();

for (const api of apis) {
  if (api.auth !== 'none') continue;
  if (api.https !== 'yes') continue;
  if (!api.host || !api.url) continue;

  const categoryMatch = RELEVANT_CATEGORIES.test(String(api.cat ?? ''));
  const textMatch = RELEVANT_TEXT.test(`${api.name} ${api.desc ?? ''}`);
  if (!categoryMatch && !textMatch) continue;

  const provider = slug(api.host);
  if (seen.has(provider)) continue;
  seen.add(provider);

  kept.push({
    provider,
    label: api.name ?? provider,
    base_url: null,
    docs_url: api.url,
    auth: 'none',
    model_family: null,
    tos: 'review',
    privacy_retention: 'unknown',
    capabilities: guessCapabilities(api),
    needs_probe: true,
    notes: `from app-endpoints: ${api.cat ?? 'uncategorised'}${api.cors === 'yes' ? ' · CORS yes' : ''} — base URL unverified`,
  });
}

kept.sort((a, b) => a.provider.localeCompare(b.provider));

const out = {
  _comment:
    'Generated by scripts/build-catalog.mjs from the app-endpoints dataset. Every entry is an unverified identity: base_url is null until the canary prober (B2.3) resolves it. Do not hand-edit; re-run the script.',
  version: 1,
  meta: {
    source: 'drsamonline/app-endpoints data/apis.json',
    sourceCount: apis.length,
    keylessCount: apis.filter((a) => a.auth === 'none').length,
    kept: kept.length,
    generatedAt: new Date().toISOString(),
    filter: 'auth=none, https=yes, category or description looks like a model endpoint',
  },
  entries: kept,
};

writeFileSync(join(ROOT, 'packages', 'catalog', 'generated.json'), JSON.stringify(out, null, 2) + '\n');

console.log('');
console.log(`Catalogue built from ${apis.length} APIs`);
console.log(`  keyless:      ${out.meta.keylessCount}`);
console.log(`  kept:         ${kept.length} (model-ish, HTTPS, no key)`);
console.log(`  categories:   ${[...new Set(kept.map((k) => k.notes.split(': ')[1]?.split(' ·')[0]))].slice(0, 8).join(', ')}`);
console.log(`  written:      packages/catalog/generated.json`);
console.log('');
console.log('Every entry is needs_probe:true with base_url:null — nothing here is routable yet.');

function slug(host) {
  return String(host)
    .toLowerCase()
    .replace(/^www\./, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40);
}

function guessCapabilities(api) {
  const text = `${api.name} ${api.desc ?? ''} ${api.cat ?? ''}`.toLowerCase();
  const caps = new Set(['chat']);
  if (/stream/.test(text)) caps.add('streaming');
  if (/translat|language/.test(text)) caps.add('chat');
  if (/embed/.test(text)) caps.add('embeddings');
  if (/image|photo|picture/.test(text)) caps.add('image');
  if (/speech|audio|voice|transcri|tts/.test(text)) caps.add('stt');
  if (/ocr|vision|classif/.test(text)) caps.add('vision');
  return [...caps];
}
